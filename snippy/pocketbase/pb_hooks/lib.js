/// Shared helpers for pb_hooks. Required from inside hook callbacks
/// (executor VMs do not see other *.pb.js top-level bindings).

const USERNAME_PATTERN = /^[a-zA-Z0-9_][a-zA-Z0-9_-]{1,31}$/;
const AUTOGEN_USERNAME = /^[a-z]{5}[0-9]{4}$/;

const ADJECTIVES = [
  'silver',
  'blue',
  'brave',
  'clever',
  'happy',
  'swift',
  'bright',
  'calm',
  'lucky',
  'gentle',
];
const NOUNS = ['otter', 'falcon', 'lion', 'panda', 'wolf', 'fox', 'tiger', 'hawk', 'bear', 'eagle'];

const RESERVED_USERNAMES = [
  'login',
  'create-account',
  'forgot-password',
  'reset-password',
  'set-password',
  'auth',
  'callback',
  'home',
  'following',
  'public',
  'tags',
  'settings',
  'collections',
  'embed',
  'try',
  'snippet',
  'privacy',
  'terms',
  'api',
  'admin',
  's',
  'me',
  'fullpage',
];

function randomShortId() {
  return $security.randomStringWithAlphabet(
    7,
    '0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ'
  );
}

function slugFromName(name) {
  return String(name || '')
    .replace(/[^a-zA-Z0-9]/g, '')
    .toLowerCase()
    .slice(0, 20);
}

function randomUsername(base) {
  const suffix = Math.floor(1000 + Math.random() * 9000);
  const cleaned = slugFromName(base);
  if (cleaned) return `${cleaned}${suffix}`;
  const adj = ADJECTIVES[Math.floor(Math.random() * ADJECTIVES.length)];
  const noun = NOUNS[Math.floor(Math.random() * NOUNS.length)];
  return `${adj}-${noun}-${suffix}`;
}

function isReservedUsername(name) {
  return RESERVED_USERNAMES.indexOf(String(name || '').toLowerCase()) !== -1;
}

function isValidUsername(name) {
  return USERNAME_PATTERN.test(String(name || '')) && !isReservedUsername(name);
}

function isAutogeneratedUsername(name) {
  return AUTOGEN_USERNAME.test(String(name || ''));
}

function usernameTaken(app, name, exceptId) {
  try {
    const rec = app.findFirstRecordByFilter('users', 'username = {:name}', { name });
    return rec && rec.id !== exceptId;
  } catch (err) {
    return false;
  }
}

function uniqueUsername(app, preferred, exceptId) {
  if (preferred && isValidUsername(preferred) && !usernameTaken(app, preferred, exceptId)) {
    return preferred;
  }
  for (let i = 0; i < 12; i++) {
    const candidate = randomUsername(preferred);
    if (!isReservedUsername(candidate) && !usernameTaken(app, candidate, exceptId)) {
      return candidate;
    }
  }
  return `user-${Date.now()}`;
}

function uniqueShortId(app, collectionName) {
  for (let i = 0; i < 12; i++) {
    const candidate = randomShortId();
    try {
      app.findFirstRecordByFilter(collectionName, 'shortId = {:id}', { id: candidate });
    } catch (err) {
      return candidate;
    }
  }
  return randomShortId() + randomShortId().slice(0, 4);
}

function relationId(value) {
  if (!value) return '';
  if (typeof value === 'string') return value;
  if (typeof value === 'object' && value.id) return String(value.id);
  return String(value);
}

// Identifiers are interpolated only from this allowlist. Values are bound.
const COUNTER_FIELDS = {
  snippets: {
    viewCount: true,
    forkCount: true,
    favoriteCount: true,
    commentCount: true,
    embedCount: true,
  },
};

function bumpCount(app, collection, id, field, delta) {
  const allowed = COUNTER_FIELDS[collection];
  if (!allowed || !allowed[field]) return 0;
  const recordId = relationId(id);
  if (!recordId) return 0;
  const n = Number(delta) || 0;
  app
    .db()
    .newQuery(
      'UPDATE ' +
        collection +
        ' SET ' +
        field +
        ' = MAX(0, IFNULL(' +
        field +
        ', 0) + {:delta}) WHERE id = {:id}'
    )
    .bind({ delta: n, id: recordId })
    .execute();
  return app.findRecordById(collection, recordId).getInt(field);
}

function assertCommentParent(app, record) {
  const parentId = relationId(record.get('parentComment'));
  if (!parentId) return;
  let parent;
  try {
    parent = app.findRecordById('comments', parentId);
  } catch (err) {
    throw new BadRequestError('Parent comment was not found');
  }
  if (relationId(parent.get('snippet')) !== relationId(record.get('snippet'))) {
    throw new BadRequestError('Reply must stay on the same snippet');
  }
}

function publicUser(user) {
  if (!user) return null;
  return {
    id: user.id,
    collectionId: user.collection().id,
    collectionName: user.collection().name,
    username: user.getString('username'),
    name: user.getString('name'),
  };
}

/** Fields the SPA mapper reads. Omits email, shareToken, and other hidden auth data. */
function publicSnippet(snippet) {
  const user = snippet.expandedOne('user');
  const payload = {
    id: snippet.id,
    collectionId: snippet.collection().id,
    collectionName: snippet.collection().name,
    user: relationId(snippet.get('user')),
    shortId: snippet.getString('shortId'),
    name: snippet.getString('name'),
    description: snippet.getString('description'),
    isPrivate: snippet.getBool('isPrivate'),
    isTemplate: snippet.getBool('isTemplate'),
    tags: snippet.get('tags'),
    cdnResources: snippet.get('cdnResources'),
    viewCount: snippet.getInt('viewCount'),
    forkCount: snippet.getInt('forkCount'),
    favoriteCount: snippet.getInt('favoriteCount'),
    commentCount: snippet.getInt('commentCount'),
    embedCount: snippet.getInt('embedCount'),
    snapshot: snippet.get('snapshot'),
    parentShortId: snippet.getString('parentShortId'),
    parentName: snippet.getString('parentName'),
    parentUserName: snippet.getString('parentUserName'),
    parentDeleted: snippet.getBool('parentDeleted'),
    created: snippet.get('created'),
    updated: snippet.get('updated'),
  };
  if (user) payload.expand = { user: publicUser(user) };
  return payload;
}

function publicFile(file) {
  return {
    id: file.id,
    fileType: file.getString('fileType'),
    content: file.getString('content'),
    snippet: relationId(file.get('snippet')),
  };
}

function publicFiles(files) {
  const out = [];
  for (const file of files) out.push(publicFile(file));
  return out;
}

function requireAuth(e) {
  if (!e.auth) {
    throw new UnauthorizedError('Authentication required');
  }
  return e.auth;
}

// HttpOnly session cookie that carries the users JWT (see 5_auth_cookie.pb.js).
const AUTH_COOKIE = 'snippy_auth';

/** The auth cookie's token, or '' when the request has none. */
function readAuthCookie(e) {
  try {
    return e.request.cookie(AUTH_COOKIE).value || '';
  } catch (err) {
    return '';
  }
}

/**
 * Secure when the public site (PB_APP_URL) is https. Not read from the request:
 * auth hook events do not expose e.request, and nginx behind a TLS proxy
 * forwards its own http scheme.
 */
function authCookieSecure(e) {
  const appUrl = String(e.app.settings().meta.appURL || '');
  return appUrl.toLowerCase().indexOf('https://') === 0;
}

/** Set (or, with an empty token, expire) the auth cookie. */
function setAuthCookie(e, token, maxAge) {
  e.setCookie(
    new Cookie({
      name: AUTH_COOKIE,
      value: token,
      path: '/api/',
      maxAge: token ? maxAge : -1,
      httpOnly: true,
      secure: authCookieSecure(e),
      sameSite: 3, // http.SameSiteStrictMode
    })
  );
}

function clearAuthCookie(e) {
  setAuthCookie(e, '', 0);
}

/**
 * True unless the browser says the request came from another origin.
 * Sec-Fetch-Site is missing on old browsers and non-browser clients; the
 * SameSite=Strict cookie still keeps cross-site requests from carrying it.
 */
function isSameOriginRequest(e) {
  const site = String(e.request.header.get('Sec-Fetch-Site') || '');
  return !site || site === 'same-origin' || site === 'none';
}

